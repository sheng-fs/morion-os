fn draw_char(x: u32, y: u32, ch: u8, color: u32) {
    if ch < 0x20 || ch > 0x7E { return; }
    let glyph = &FONT[(ch - 0x20) as usize];
    for row in 0..16u32 {
        let bits = glyph[row as usize];
        for col in 0..8u32 {
            if bits & (0x80 >> col) != 0 {
                unsafe { FB.pixel(x + col, y + row, color); }
            }
        }
    }
}

fn draw_text(x: u32, y: u32, s: &str, color: u32) {
    for (i, ch) in s.bytes().enumerate() {
        draw_char(x + i as u32 * 8, y, ch, color);
    }
}

