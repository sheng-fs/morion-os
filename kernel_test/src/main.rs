// ============================================================
//  Boot Info 结构 (引导器 → 内核)
// ============================================================

#[repr(C)]
struct BootInfo {
    magic: u32,      // 0x4D4F5249 = "MORI"
    version: u32,    // 1
    fb_addr: u64,    // 帧缓冲物理地址
    fb_width: u32,   // 宽度 (像素)
    fb_height: u32,  // 高度 (像素)
    fb_stride: u32,  // 行跨度 (像素)
    fb_bpp: u32,     // 每像素位数
}

const BOOT_INFO_ADDR: *const BootInfo = 0x7000 as *const BootInfo;

// ============================================================
//  全局帧缓冲状态
// ============================================================

static mut FB: Framebuffer = Framebuffer {
    base: 0 as *mut u8,
    width: 0,
    height: 0,
    stride: 0,
};

struct Framebuffer {
    base: *mut u8,
    width: u32,
    height: u32,
    stride: u32,
}

impl Framebuffer {
    fn pixel(&mut self, x: u32, y: u32, color: u32) {
        if x < self.width && y < self.height {
            let off = (y * self.stride + x) as usize * 4;
            unsafe {
                *self.base.add(off) = (color & 0xFF) as u8;
                *self.base.add(off + 1) = ((color >> 8) & 0xFF) as u8;
                *self.base.add(off + 2) = ((color >> 16) & 0xFF) as u8;
                *self.base.add(off + 3) = 0xFF;
            }
        }
    }

    fn fill_rect(&mut self, x: u32, y: u32, w: u32, h: u32, color: u32) {
        for dy in 0..h {
            for dx in 0..w {
                self.pixel(x + dx, y + dy, color);
            }
        }
    }
}

