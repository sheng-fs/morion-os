#[panic_handler]
fn panic(_info: &PanicInfo) -> ! {
    unsafe {
        if FB.width > 0 {
            FB.fill_rect(0, 0, FB.width, FB.height, 0x000033);
            draw_text(20, 20, "KERNEL PANIC", 0xFF0000);
            draw_text(20, 44, "An unrecoverable error occurred.", 0xFF8888);
        }
    }
    halt();
}