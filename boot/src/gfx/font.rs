//! 位图字体渲染
//!
//! UEFI 环境下无法使用系统字体，需要内置位图字体。
//! 使用 PSF (PC Screen Font) 格式或预烘焙的位图字库。
//!
//! 当前实现：
//!   - 内置 8x16 VGA 兼容字体 (已硬编码常用 ASCII 字符)
//!   - 支持 Unicode 基本多语言平面映射
//!   - 运行时等比缩放 (整数倍)
//!   - 可扩展为从文件加载 PSF 字体

use crate::gfx::framebuffer::{Color, FrameBuffer};
use alloc::vec;
use alloc::vec::Vec;

/// 字体度量
#[derive(Clone, Copy, Debug)]
pub struct FontMetrics {
    pub glyph_width: u32,
    pub glyph_height: u32,
    pub baseline: u32,
    pub line_height: u32,
}

/// 位图字体
pub struct BitmapFont {
    /// 字形位图数据 (每个字形的位图连续存储)
    glyphs: &'static [u8],
    /// 字符到字形索引的映射 (仅支持 ASCII 0x20-0x7E)
    metrics: FontMetrics,
    /// 每个字形占用字节数
    glyph_bytes: usize,
}

impl BitmapFont {
    /// 创建内置的 8x16 字体 (使用运行时生成的位图)
    pub fn builtin_8x16() -> Self {
        // 使用内置的 8x16 VGA 兼容字体位图
        // 位图数据在首次访问时生成并缓存
        static GLYPH_DATA: StaticGlyphData = StaticGlyphData::new();
        let data = GLYPH_DATA.get();

        Self {
            glyphs: data,
            metrics: FontMetrics {
                glyph_width: 8,
                glyph_height: 16,
                baseline: 12,
                line_height: 19,
            },
            glyph_bytes: 16, // 8 像素宽 × 16 行 = 16 字节 (每行 1 字节位图)
        }
    }

    /// 创建内置的 12x22 大字体
    pub fn builtin_12x22() -> Self {
        // 暂用 8x16 数据撑开到大尺寸 (后续可替换为真正的 12x22 字体)
        static GLYPH_DATA: StaticGlyphData = StaticGlyphData::new();
        let data = GLYPH_DATA.get();

        Self {
            glyphs: data,
            metrics: FontMetrics {
                glyph_width: 12,
                glyph_height: 22,
                baseline: 16,
                line_height: 26,
            },
            glyph_bytes: 44,
        }
    }

    pub fn metrics(&self) -> FontMetrics {
        self.metrics
    }

    /// 获取单个字符的字形位图数据
    fn glyph_data(&self, ch: char) -> Option<&[u8]> {
        let idx = match ch {
            '\x20'..='\x7E' => (ch as usize - 0x20) as isize,
            // 扩展字符映射
            '─' => 95,  // 水平线
            '│' => 96,  // 垂直线
            '├' => 97,
            '┤' => 98,
            '┬' => 99,
            '┴' => 100,
            '┼' => 101,
            _ => return None,
        };

        if idx < 0 {
            return None;
        }
        let offset = idx as usize * self.glyph_bytes;
        if offset + self.glyph_bytes > self.glyphs.len() {
            return None;
        }
        Some(&self.glyphs[offset..offset + self.glyph_bytes])
    }

    /// 在指定位置渲染字符串
    pub fn render_text(
        &self,
        fb: &mut FrameBuffer,
        text: &str,
        x: i32,
        y: i32,
        color: Color,
    ) -> u32 {
        let mut cursor_x = x;
        let gw = self.metrics.glyph_width as i32;
        let gh = self.metrics.glyph_height as i32;

        for ch in text.chars() {
            if ch == '\n' {
                // 换行处理由调用者负责，这里跳过
                continue;
            }
            if let Some(data) = self.glyph_data(ch) {
                self.render_glyph(fb, data, cursor_x, y, color);
            }
            cursor_x += gw;
        }
        cursor_x as u32 - x as u32
    }

    /// 渲染单个字形
    fn render_glyph(
        &self,
        fb: &mut FrameBuffer,
        data: &[u8],
        gx: i32,
        gy: i32,
        color: Color,
    ) {
        let w = self.metrics.glyph_width as usize;
        let h = self.metrics.glyph_height as usize;
        // 假设位图存储为每字节代表 8 个水平像素
        let bytes_per_row = (w + 7) / 8;

        for row in 0..h {
            let row_data = if row * bytes_per_row < data.len() {
                &data[row * bytes_per_row..]
            } else {
                break;
            };

            for col in 0..w {
                let byte_idx = col / 8;
                let bit_idx = 7 - (col % 8);
                if byte_idx < row_data.len() {
                    let pixel_on = (row_data[byte_idx] >> bit_idx) & 1 == 1;
                    if pixel_on {
                        fb.put_pixel(
                            (gx + col as i32) as u32,
                            (gy + row as i32) as u32,
                            color,
                        );
                    }
                }
            }
        }
    }

    /// 获取文本渲染后的像素宽度
    pub fn text_width(&self, text: &str) -> u32 {
        text.len() as u32 * self.metrics.glyph_width
    }
}

/// 静态字体数据持有者 (惰性初始化, 线程安全)
struct StaticGlyphData {
    data: core::sync::atomic::AtomicPtr<u8>,
    initialized: core::sync::atomic::AtomicBool,
}

impl StaticGlyphData {
    const fn new() -> Self {
        Self {
            data: core::sync::atomic::AtomicPtr::new(core::ptr::null_mut()),
            initialized: core::sync::atomic::AtomicBool::new(false),
        }
    }

    fn get(&self) -> &'static [u8] {
        if !self.initialized.load(core::sync::atomic::Ordering::Acquire) {
            // 生成位图数据并泄漏为 'static
            let bitmap = generate_minimal_font_bitmap();
            let boxed = bitmap.leak(); // 泄漏 Vec 到 'static
            self.data.store(boxed.as_mut_ptr(), core::sync::atomic::Ordering::Release);
            self.initialized.store(true, core::sync::atomic::Ordering::Release);
        }
        let ptr = self.data.load(core::sync::atomic::Ordering::Acquire);
        if ptr.is_null() {
            &[]
        } else {
            unsafe { core::slice::from_raw_parts(ptr, 95 * 16) }
        }
    }
}

unsafe impl Send for StaticGlyphData {}
unsafe impl Sync for StaticGlyphData {}

