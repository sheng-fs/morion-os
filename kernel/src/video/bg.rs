//! 文本控制台背景 — 由 `resources/system/terminal/终端背景_1024x768.raw` 提取的竖直渐变。
//!
//! 壁纸本身是「上黑下灰」的平滑竖直渐变 (1024x575, RGB888)。直接内嵌整幅图会让内核
//! 镜像增长约 1.7 MB, 在加载阶段可能覆盖引导器仍在使用的页表 (见文档中 triple fault
//! 一节的教训)。故这里只保留 **64 级竖直颜色表** (256 字节), 运行时按帧缓冲高度线性
//! 插值铺满, 分辨率无关且重绘开销极低。
//!
//! 颜色已按 `GAIN`/`TINT_*` 压暗并偏蓝: 原图底部达中灰 (~128), 不压暗则白色文字不可读。

/// 竖直渐变色表 (自顶向下), 24 位 `0x00RRGGBB`。
pub const PROFILE: [u32; 64] = [
    0x0D0E12, 0x000000, 0x000000, 0x000000, 0x000000, 0x000000, 0x000000, 0x000000,
    0x000000, 0x000000, 0x000000, 0x000000, 0x000000, 0x000000, 0x000000, 0x000000,
    0x000000, 0x000000, 0x000000, 0x000000, 0x000000, 0x000000, 0x000000, 0x000000,
    0x010102, 0x020203, 0x040406, 0x050507, 0x060608, 0x08080B, 0x09090C, 0x090A0D,
    0x0B0C10, 0x0C0D11, 0x0D0E12, 0x0E0F14, 0x0F1015, 0x111217, 0x121319, 0x13141B,
    0x14151C, 0x16171F, 0x181921, 0x191A23, 0x1B1D26, 0x1C1E28, 0x1E202A, 0x20222D,
    0x21232E, 0x232530, 0x242633, 0x252734, 0x282A38, 0x292B39, 0x2B2D3C, 0x2C2E3D,
    0x2D303F, 0x2E3141, 0x303343, 0x303343, 0x323546, 0x333647, 0x343748, 0x343748,
];

/// 采样: 返回屏幕第 `y` 行 (共 `screen_h` 行) 的背景色 (线性插值)。
pub fn color_for_row(y: u32, screen_h: u32) -> u32 {
    if screen_h <= 1 {
        return PROFILE[PROFILE.len() - 1];
    }
    let y = if y >= screen_h { screen_h - 1 } else { y };
    // t = y / (screen_h - 1), 映射到 [0, PROFILE.len()-1]
    let num = (PROFILE.len() - 1) as u64 * y as u64;
    let den = (screen_h - 1) as u64;
    let i = (num / den) as usize;
    PROFILE[i]
}
