//! 启动 LOGO — 按系统 Logo（`resources/system/logo/`）的几何构成手工编排的 ASCII 图。
//!
//! 为什么不直接对 PNG 采样: 源图是「深色烟团圆盘 + 亮白电路十字」, 缩到 60x26 的字符
//! 网格后, 电路那条 ~6px 的细白线只有不到一个字符宽, 降采样后时有时无 —— 形状糊掉、
//! 认不出是哪个 Logo。故改为按几何直接编排: 烟团用高斯圆环得强度, 电路十字/方框/焊点
//! 用高密度字符压上去, 细线永远清晰。
//!
//! 生成规则（可复现）:
//! ```text
//! 字符单元 8 宽 x 20 行距 (LINE_HEIGHT), 故屏幕上要接近正圆需 cols:rows = 2.5:1。
//! 取 61 x 25 网格 (61*8 = 488 px 宽, 25*20 = 500 px 高)。
//! 1. 烟团: 屏幕像素坐标下到圆心距离 d, 强度 = exp(-((d-228)/11)^2), 映射到
//!    " .:-=+" 5 级 (取 RAMP[0..=4], 见 `RAMP`)。
//! 2. 电路: 竖线 '|' (col 30, row 3..=21)、横线 '-' (row 12, col 10..=50)、
//!    四端焊点 'o'、中心方框 '#' (row 10..=14, col 25..=35)、方框两侧短刻线 '.'。
//! ```
//!
//! 打印时由 [`super::print_logo`] 按**整块**居中 (常量左缩进), 不可逐行居中,
//! 否则每行各自居中会把图形横向错切。

/// 亮度字符集: 由暗到亮 (越亮字符越密)。烟团只用前 6 级, 电路用高级字符。
pub const RAMP: &str = " .:-=+*#%@";

/// LOGO 各行的最大显示宽度 (字符数), 供整块居中计算。
pub const WIDTH: usize = 61;

