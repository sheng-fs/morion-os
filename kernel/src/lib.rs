//! Morion OS 微内核库
//!
//! 这是系统的唯一可信计算基 (TCB)。
//! 仅实现:
//!   - 地址空间隔离 (页表管理)
//!   - 进程间通信 (IPC + 能力传递)
//!   - CPU 调度 (抢占式)
//!   - 能力强制 (每个系统调用均校验)
//!   - 硬件中断路由 (中断 → IPC 消息)
//!
//! 所有其他功能 (文件系统、网络、驱动、认证) 均为用户态服务。

#![no_std]
#![feature(asm_experimental_arch)]
#![allow(dead_code)]

// ============================================================
// 模块声明
// ============================================================

/// 引导信息 (UEFI 传递 → 引导器 → 内核)
pub mod boot;

/// 架构特定代码
pub mod arch;

/// 内存管理 (物理 + 虚拟)
pub mod mm;

/// 进程间通信
pub mod ipc;

/// 任务/进程管理
pub mod task;

/// 能力安全模型
pub mod cap;

/// 极简系统调用接口 (10~20 个)
pub mod syscall;

/// 调试/日志
pub mod debug;

/// 串口输出 (COM1, 0x3F8)
pub mod serial;

// ============================================================
// 重新导出常用项
// ============================================================
pub use boot::BootInfo;
pub use syscall::SyscallNumber;
